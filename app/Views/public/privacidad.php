        <div class="content" style="color: #334155; line-height: 1.75; font-size: 15px;">
            <p>
                En <strong>CONEX</strong> (operado por Softlutionic, en adelante "la Plataforma"), nos comprometemos a proteger la privacidad y seguridad de los datos personales de nuestros usuarios. Esta Política de Privacidad describe cómo recopilamos, utilizamos, almacenamos y protegemos la información a través de nuestro sitio web y nuestra aplicación móvil para Android.
            </p>

            <h3 class="fw-bold mt-4 mb-3" style="color: #1B2A4A;">1. Información que recopilamos</h3>
            <p>Para brindar nuestros servicios de conexión laboral y prestación de oficios, recopilamos las siguientes categorías de datos personales:</p>
            <ul>
                <li><strong>Información de registro y contacto:</strong> Nombre, apellidos, dirección de correo electrónico, número de teléfono celular y contraseña cifrada.</li>
                <li><strong>Perfil profesional y laboral:</strong> Profesión u oficio, nivel de experiencia, resumen profesional ("Sobre mí"), habilidades técnicas, historial de empleos anteriores y formación académica.</li>
                <li><strong>Verificación de identidad:</strong> Número de cédula de identidad y fecha de nacimiento. En la app móvil, el usuario puede escanear su cédula para autocompletar su registro de forma segura.</li>
                <li><strong>Documentos y archivos:</strong> Currículum Vitae (CV) en formato PDF o Word y fotografía de perfil (avatar).</li>
                <li><strong>Ubicación geográfica:</strong> Datos de ubicación aproximada o precisa (coordenadas GPS) proporcionados por el dispositivo móvil cuando el usuario activa la búsqueda por cercanía o el mapa interactivo.</li>
            </ul>

            <h3 class="fw-bold mt-4 mb-3" style="color: #1B2A4A;">2. Uso de Permisos en la Aplicación Móvil</h3>
            <p>Nuestra aplicación Android solicita los siguientes permisos para su correcto funcionamiento:</p>
            <ul>
                <li><strong>Ubicación en primer plano (ACCESS_FINE_LOCATION y ACCESS_COARSE_LOCATION):</strong> Utilizada exclusivamente cuando el usuario utiliza la app para mostrar ofertas de empleo cercanas, prestadores disponibles en su zona y posicionar su pin en el mapa si ofrece servicios. <em>No rastreamos la ubicación en segundo plano sin conocimiento del usuario.</em></li>
                <li><strong>Cámara (CAMERA):</strong> Utilizada para la captura del código de la cédula de identidad durante el registro opcional y para la toma de fotografía de perfil.</li>
                <li><strong>Almacenamiento y archivos:</strong> Utilizado únicamente para permitir al usuario seleccionar y subir su archivo de currículum vitae o imagen de avatar desde su dispositivo.</li>
            </ul>

            <h3 class="fw-bold mt-4 mb-3" style="color: #1B2A4A;">3. Finalidad del Tratamiento de los Datos</h3>
            <p>Los datos personales recolectados se utilizan estrictamente para:</p>
            <ul>
                <li>Conectar postulantes con vacantes de empleo publicadas por empresas verificadas.</li>
                <li>Permitir que clientes encuentren y contacten a prestadores de servicios independientes y oficios calificados.</li>
                <li>Gestionar solicitudes de contacto y postulaciones.</li>
                <li>Garantizar la autenticidad y seguridad de las cuentas de usuario.</li>
            </ul>

            <h3 class="fw-bold mt-4 mb-3" style="color: #1B2A4A;">4. Privacidad del Prestador y Contacto Seguro</h3>
            <p>
                CONEX protege el número de teléfono del usuario: en el directorio y mapa público solo se muestra el nombre público (ej. "Juan P.") y oficio. El número de teléfono solo se revela entre postulante y empleador / cliente cuando una solicitud de contacto ha sido formalmente aceptada por ambas partes.
            </p>

            <h3 class="fw-bold mt-4 mb-3" style="color: #1B2A4A;">5. Seguridad y Cifrado</h3>
            <p>
                Toda la comunicación entre la aplicación móvil, nuestro sitio web y los servidores se transmite de forma cifrada mediante el protocolo <strong>HTTPS / TLS</strong>. Las contraseñas se almacenan mediante algoritmos de hash seguros (BCrypt) y nunca en texto plano.
            </p>

            <h3 class="fw-bold mt-4 mb-3" style="color: #1B2A4A;">6. Retención y Eliminación de Datos (Derechos del Usuario)</h3>
            <p>
                Los usuarios tienen derecho en todo momento a acceder, rectificar o eliminar su cuenta y todos sus datos personales asociados:
            </p>
            <ul>
                <li><strong>Desde la aplicación móvil:</strong> Ingresando a la pestaña <em>Perfil &gt; Configuración de Cuenta &gt; Eliminar mi cuenta</em>.</li>
                <li><strong>Desde la web:</strong> A través de nuestro portal público de eliminación de cuenta en <a href="<?= base_url('eliminar-cuenta') ?>" class="fw-semibold text-decoration-none" style="color: #F97316;">conex.softlutionic.com/eliminar-cuenta</a>.</li>
            </ul>
            <p>Al confirmar la eliminación, la cuenta, los currículums, fotografías y fichas de servicio son dados de baja y eliminados de forma permanente de nuestra base de datos activa.</p>

